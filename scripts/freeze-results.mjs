// Freeze the OpenFootball 2026 results feed into a committed snapshot.
//
// The app reads final scores from OpenFootball at runtime (see
// src/services/results.js). That is a single external dependency: if the feed
// is moved, restructured, or taken down, a finished tournament's scores would
// vanish from the app with nothing to fall back on. This script captures the
// feed once, as it stands, into src/data/finalResults.js. The app builds a
// results map from that committed copy and uses it whenever the live fetch
// fails, so the scores survive independently of OpenFootball staying up.
//
// It keeps only the fields the app's parser reads (see buildResultsMap in
// src/services/results.js): round, num, team1, team2, score, goals1, goals2.
// The snapshot is processed by the SAME parser as the live feed, so the two
// paths cannot drift.
//
// Run once after the tournament is final (or to refresh the snapshot):
//   node scripts/freeze-results.mjs

import { writeFile } from 'node:fs/promises'
import { fileURLToPath } from 'node:url'
import { dirname, resolve } from 'node:path'
import { RESULTS_SOURCE } from '../src/services/results.js'

const OUT = resolve(dirname(fileURLToPath(import.meta.url)), '../src/data/finalResults.js')

// Only the fields the parser reads. Anything undefined is dropped so the
// snapshot stays lean and its diff stays readable.
function trimMatch(m) {
  const out = { round: m.round }
  if (m.num != null) out.num = m.num
  out.team1 = m.team1
  out.team2 = m.team2
  if (m.score) out.score = m.score
  if (Array.isArray(m.goals1) && m.goals1.length) out.goals1 = m.goals1
  if (Array.isArray(m.goals2) && m.goals2.length) out.goals2 = m.goals2
  return out
}

async function main() {
  const res = await fetch(RESULTS_SOURCE.url, { cache: 'no-store' })
  if (!res.ok) throw new Error(`Feed request failed (HTTP ${res.status})`)
  const data = await res.json()
  if (!Array.isArray(data.matches)) throw new Error('Feed is missing a matches[] array')

  const matches = data.matches.map(trimMatch)
  const scored = matches.filter((m) => m.score && Array.isArray(m.score.ft)).length

  const header = `// GENERATED by scripts/freeze-results.mjs — do not edit by hand.
//
// A frozen snapshot of the OpenFootball 2026 World Cup results feed, used as a
// committed fallback so final scores survive even if the live feed becomes
// unreachable or changes shape. It is parsed by buildResultsMap in
// src/services/results.js, the same code path as the live feed.
//
// Source: ${RESULTS_SOURCE.url}
// Frozen: ${new Date().toISOString().slice(0, 10)} (${scored} of ${matches.length} matches final)
// Regenerate: node scripts/freeze-results.mjs

export const FINAL_RESULTS = ${JSON.stringify(matches, null, 2)}
`
  await writeFile(OUT, header)
  console.log(`Wrote ${OUT}`)
  console.log(`  ${matches.length} matches, ${scored} with a final score`)
}

main()
